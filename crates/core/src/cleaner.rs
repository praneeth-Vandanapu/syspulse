fn is_rotated_log(name: &str) -> bool {
    name.ends_with(".gz")
        || name.ends_with(".xz")
        || name.ends_with(".old")
        || name
            .rsplit_once('.')
            .is_some_and(|(_, ext)| !ext.is_empty() && ext.bytes().all(|b| b.is_ascii_digit()))
}

fn rotated_logs() -> Vec<PathBuf> {
    jwalk::WalkDir::new("/var/log")
        .skip_hidden(false)
        .process_read_dir(|_, _, _, children| {
            children.retain(|c| {
                c.as_ref()
                    .map(|e| e.file_name() != "journal")
                    .unwrap_or(false)
            });
        })
        .into_iter()
        .filter_map(std::result::Result::ok)
        .filter(|e| e.file_type().is_file() && is_rotated_log(&e.file_name().to_string_lossy()))
        .map(|e| e.path())
        .collect()
}

fn files_in(dir: &str, pred: impl Fn(&str) -> bool) -> Vec<PathBuf> {
    fs::read_dir(dir)
        .map(|rd| {
            rd.filter_map(std::result::Result::ok)
                .filter(|e| pred(&e.file_name().to_string_lossy()))
                .map(|e| e.path())
                .collect()
        })
        .unwrap_or_default()
}

fn sum_sizes(paths: &[PathBuf]) -> u64 {
    paths
        .iter()
        .filter_map(|p| fs::symlink_metadata(p).ok())
        .map(|m| fsutil::allocated(&m))
        .sum()
}

const JOURNAL_KEEP: u64 = 100 * 1024 * 1024;

#[cfg(target_os = "linux")]
fn system_targets() -> Vec<CleanTarget> {
    let mk =
        |id: &str, title: &str, desc: &str, paths: &[&str], size: u64, files: u64| CleanTarget {
            id: id.into(),
            title: title.into(),
            description: desc.into(),
            category: Category::System,
            paths: paths.iter().map(|s| s.to_string()).collect(),
            size,
            files,
            needs_admin: true,
            caution: None,
            selected_by_default: true,
            details: Vec::new(),
        };

    let debs = files_in("/var/cache/apt/archives", |n| n.ends_with(".deb"));
    let partial = files_in("/var/cache/apt/archives/partial", |_| true);
    let journal = usage(Path::new("/var/log/journal"), None).bytes;
    let logs = rotated_logs();
    let crashes = files_in("/var/crash", |n| {
        n.ends_with(".crash") || n.ends_with(".upload") || n.ends_with(".uploaded")
    });
    let cores = files_in("/var/lib/systemd/coredump", |_| true);
    let snaps = crate::software::snap::old_revisions();
    let (auto, auto_bytes) = crate::software::apt_autoremovable();

    let mut v = vec![
        mk(
            "apt-cache",
            "APT package cache",
            "Downloaded .deb installers kept after updates",
            &["/var/cache/apt/archives"],
            sum_sizes(&debs) + sum_sizes(&partial),
            (debs.len() + partial.len()) as u64,
        ),
        mk(
            "journal",
            "System journal logs",
            "Keeps the newest 100 MB of logs, removes older ones",
            &["/var/log/journal"],
            journal.saturating_sub(JOURNAL_KEEP),
            0,
        ),
        mk(
            "rotated-logs",
            "Old rotated logs",
            "Compressed and rotated log files (*.gz, *.1, *.old)",
            &["/var/log"],
            sum_sizes(&logs),
            logs.len() as u64,
        ),
        mk(
            "crash-reports",
            "Crash reports",
            "Application crash reports collected by Apport",
            &["/var/crash"],
            sum_sizes(&crashes),
            crashes.len() as u64,
        ),
        mk(
            "coredumps",
            "Core dumps",
            "Memory dumps of crashed programs",
            &["/var/lib/systemd/coredump"],
            sum_sizes(&cores),
            cores.len() as u64,
        ),
    ];
    let mut snap_t = mk(
        "snap-revisions",
        "Old Snap revisions",
        "Previous versions snapd keeps for rollback",
        &["/var/lib/snapd/snaps"],
        snaps.iter().map(|r| r.size).sum(),
        snaps.len() as u64,
    );
    snap_t.details = snaps
        .iter()
        .map(|r| {
            format!(
                "{} (rev {}) — {}",
                r.name,
                r.revision,
                crate::util::human_bytes(r.size)
            )
        })
        .collect();
    v.push(snap_t);
    let mut auto_t = mk(
        "autoremove",
        "Unused packages & old kernels",
        "Dependencies no longer needed by any installed package (apt autoremove)",
        &["apt-get autoremove --purge"],
        auto_bytes,
        auto.len() as u64,
    );
    auto_t.caution = Some("Review the package list before cleaning".into());
    auto_t.selected_by_default = false;
    auto_t.details = auto;
    v.push(auto_t);
    v
}

#[cfg(not(target_os = "linux"))]
fn system_targets() -> Vec<CleanTarget> {
    Vec::new()
}

/// Scan every target. `home` is the user's home directory.
pub fn scan(home: &Path) -> Vec<CleanTarget> {
    let (mut sys, user) = std::thread::scope(|s| {
        let sys = s.spawn(system_targets);
        let user = s.spawn(|| user_targets(home));
        (
            sys.join().unwrap_or_default(),
            user.join().unwrap_or_default(),
        )
    });
    sys.extend(user);
    sys
}

/// Clean user-level targets (runs as the user, no privileges).
pub fn clean_user(ids: &[String], home: &Path) -> CleanReport {
    let mut r = CleanReport::default();
    for id in ids {
        if id == "tracker" {
            // Stop and reset the indexer properly; plain deletion would race the running miner.
            // `tracker3 reset` asks for confirmation on stdin.
            if let Ok(mut child) = std::process::Command::new("tracker3")
                .args(["reset", "-s", "-r"])
                .stdin(std::process::Stdio::piped())
                .stdout(std::process::Stdio::null())
                .stderr(std::process::Stdio::null())
                .spawn()
            {
                if let Some(mut stdin) = child.stdin.take() {
                    use std::io::Write;
                    let _ = stdin.write_all(b"y\n");
                }
                let _ = child.wait();
            }
        }
        let freed: u64 = if let Some(d) = USER_DEFS.iter().find(|d| d.id == id) {
            d.paths
                .iter()
                .map(|p| home.join(p))
                .filter(|p| p.is_dir())
                .map(|p| clear_dir(&p))
                .sum()
        } else {
            match id.as_str() {
                "conda" => conda_archives(home)
                    .iter()
                    .filter_map(|p| fsutil::remove_path(p).ok())
                    .sum(),
                "flatpak-app-caches" => flatpak_app_caches(home).iter().map(|p| clear_dir(p)).sum(),
                "other-cache" => other_cache_entries(home)
                    .iter()
                    .filter_map(|p| fsutil::remove_path(p).ok())
                    .sum(),
                _ => {
                    r.errors.push(format!("unknown target {id}"));
                    continue;
                }
            }
        };
        r.freed_bytes += freed;
        r.cleaned.push(id.clone());
    }
    r
}

pub const SYSTEM_TARGET_IDS: [&str; 7] = [
    "apt-cache",
    "journal",
    "rotated-logs",
    "crash-reports",
    "coredumps",
    "snap-revisions",
    "autoremove",
];

/// Clean one system target. Must run as root (privileged helper only).
#[cfg(target_os = "linux")]
pub fn clean_system(id: &str) -> Result<u64> {
    use crate::software::run_tool as run;
    let remove_all = |paths: Vec<PathBuf>| {
        paths
            .iter()
            .filter_map(|p| fsutil::remove_path(p).ok())
            .sum::<u64>()
    };
    match id {
        "apt-cache" => {
            let before = sum_sizes(&files_in("/var/cache/apt/archives", |n| {
                n.ends_with(".deb")
            }));
            run("apt-get", &["clean"])?;
            Ok(before)
        }
        "journal" => {
            let before = usage(Path::new("/var/log/journal"), None).bytes;
            run("journalctl", &["--vacuum-size=100M"])?;
            Ok(before.saturating_sub(usage(Path::new("/var/log/journal"), None).bytes))
        }
        "rotated-logs" => Ok(remove_all(rotated_logs())),
        "crash-reports" => Ok(remove_all(files_in("/var/crash", |n| {
            n.ends_with(".crash") || n.ends_with(".upload") || n.ends_with(".uploaded")
        }))),
        "coredumps" => Ok(remove_all(files_in("/var/lib/systemd/coredump", |_| true))),
        "snap-revisions" => crate::software::snap::remove_old_revisions(),
        "autoremove" => {
            let (_, bytes) = crate::software::apt_autoremovable();
            run("apt-get", &["-y", "autoremove", "--purge"])?;
            Ok(bytes)
        }
        _ => Err(CoreError::Refused(format!("unknown system target {id}"))),
    }
}

#[cfg(not(target_os = "linux"))]
pub fn clean_system(_id: &str) -> Result<u64> {
    Err(CoreError::Unsupported("system cleaning"))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn rotated_log_names() {
        assert!(is_rotated_log("syslog.1"));
        assert!(is_rotated_log("kern.log.2.gz"));
        assert!(is_rotated_log("dpkg.log.old"));
        assert!(!is_rotated_log("syslog"));
        assert!(!is_rotated_log("Xorg.0.log"));
    }

    #[test]
    fn user_targets_cleanup_in_temp_home() {
        let home = std::env::temp_dir().join(format!("syspulse-home-{}", std::process::id()));
        fs::create_dir_all(home.join(".cache/thumbnails/large")).unwrap();
        fs::write(home.join(".cache/thumbnails/large/x.png"), vec![0u8; 8192]).unwrap();
        fs::create_dir_all(home.join(".cache/someapp")).unwrap();
        fs::write(home.join(".cache/someapp/blob"), vec![0u8; 8192]).unwrap();
        let t = user_targets(&home);
        let thumbs = t.iter().find(|x| x.id == "thumbnails").unwrap();
        assert!(thumbs.size >= 8192);
        let other = t.iter().find(|x| x.id == "other-cache").unwrap();
        assert!(
            other.size >= 8192,
            "other-cache must exclude covered dirs but include someapp"
        );
        let r = clean_user(&["thumbnails".into()], &home);
        assert!(r.freed_bytes >= 8192);
        assert!(home.join(".cache/thumbnails").exists());
        assert!(
            home.join(".cache/someapp/blob").exists(),
            "other caches untouched"
        );
        fs::remove_dir_all(&home).unwrap();
    }
}
