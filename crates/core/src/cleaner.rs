/// Conda package archives (only *.tar.bz2 / *.conda files at the pkgs root).
const CONDA_PKGS: [&str; 4] = [
    "anaconda3/pkgs",
    "miniconda3/pkgs",
    "miniforge3/pkgs",
    "mambaforge/pkgs",
];

fn conda_archives(home: &Path) -> Vec<PathBuf> {
    CONDA_PKGS
        .iter()
        .filter_map(|d| fs::read_dir(home.join(d)).ok())
        .flat_map(|rd| rd.filter_map(std::result::Result::ok))
        .map(|e| e.path())
        .filter(|p| {
            let n = p.file_name().and_then(|n| n.to_str()).unwrap_or("");
            p.is_file() && (n.ends_with(".tar.bz2") || n.ends_with(".conda"))
        })
        .collect()
}

/// Top-level ~/.cache entries owned by a dedicated target.
fn covered_cache_entries() -> Vec<&'static str> {
    let mut v: Vec<&str> = USER_DEFS
        .iter()
        .flat_map(|d| d.paths.iter())
        .filter_map(|p| p.strip_prefix(".cache/"))
        .map(|p| p.split('/').next().unwrap_or(p))
        .collect();
    v.sort_unstable();
    v.dedup();
    v
}

fn other_cache_entries(home: &Path) -> Vec<PathBuf> {
    let covered = covered_cache_entries();
    fs::read_dir(home.join(".cache"))
        .map(|rd| {
            rd.filter_map(std::result::Result::ok)
                .filter(|e| !covered.contains(&e.file_name().to_string_lossy().as_ref()))
                .map(|e| e.path())
                .collect()
        })
        .unwrap_or_default()
}

fn flatpak_app_caches(home: &Path) -> Vec<PathBuf> {
    fs::read_dir(home.join(".var/app"))
        .map(|rd| {
            rd.filter_map(std::result::Result::ok)
                .map(|e| e.path().join("cache"))
                .filter(|p| p.is_dir())
                .collect()
        })
        .unwrap_or_default()
}

fn display(p: &Path, home: &Path) -> String {
    match p.strip_prefix(home) {
        Ok(rel) => format!("~/{}", rel.display()),
        Err(_) => p.display().to_string(),
    }
}

fn user_targets(home: &Path) -> Vec<CleanTarget> {
    let mut out: Vec<CleanTarget> = std::thread::scope(|s| {
        let handles: Vec<_> = USER_DEFS
            .iter()
            .map(|d| {
                s.spawn(move || {
                    let paths: Vec<PathBuf> = d
                        .paths
                        .iter()
                        .map(|p| home.join(p))
                        .filter(|p| p.exists())
                        .collect();
                    let (mut size, mut files) = (0, 0);
                    for p in &paths {
                        let u = usage(p, None);
                        size += u.bytes;
                        files += u.files;
                    }
                    CleanTarget {
                        id: d.id.into(),
                        title: d.title.into(),
                        description: d.description.into(),
                        category: d.category,
                        paths: paths.iter().map(|p| display(p, home)).collect(),
                        size,
                        files,
                        needs_admin: false,
                        caution: d.caution.map(str::to_string),
                        selected_by_default: d.default,
                        details: Vec::new(),
                    }
                })
            })
            .collect();
        handles.into_iter().filter_map(|h| h.join().ok()).collect()
    });

    let conda = conda_archives(home);
    if !conda.is_empty() {
        let size = conda
            .iter()
            .filter_map(|p| fs::metadata(p).ok())
            .map(|m| fsutil::allocated(&m))
            .sum();
        out.push(CleanTarget {
            id: "conda".into(),
            title: "Conda package archives".into(),
            description: "Downloaded package tarballs (installed environments are not touched)"
                .into(),
            category: Category::Developer,
            paths: CONDA_PKGS
                .iter()
                .filter(|d| home.join(d).is_dir())
                .map(|d| format!("~/{d}/*.tar.bz2, *.conda"))
                .collect(),
            size,
            files: conda.len() as u64,
            needs_admin: false,
            caution: None,
            selected_by_default: true,
            details: Vec::new(),
        });
    }

    let fp = flatpak_app_caches(home);
    if !fp.is_empty() {
        let (size, files) = fp
            .iter()
            .map(|p| usage(p, None))
            .fold((0, 0), |a, u| (a.0 + u.bytes, a.1 + u.files));
        out.push(CleanTarget {
            id: "flatpak-app-caches".into(),
            title: "Flatpak app caches".into(),
            description: "Cache folders of sandboxed Flatpak applications".into(),
            category: Category::User,
            paths: vec!["~/.var/app/*/cache".into()],
            size,
            files,
            needs_admin: false,
            caution: None,
            selected_by_default: true,
            details: Vec::new(),
        });
    }

    let other = other_cache_entries(home);
    let (size, files) = other
        .iter()
        .map(|p| usage(p, None))
        .fold((0, 0), |a, u| (a.0 + u.bytes, a.1 + u.files));
    let mut biggest: Vec<(u64, String)> = other
        .iter()
        .map(|p| (usage(p, None).bytes, display(p, home)))
        .collect();
    biggest.sort_by_key(|b| std::cmp::Reverse(b.0));
    out.push(CleanTarget {
        id: "other-cache".into(),
        title: "Other application caches".into(),
        description: "Everything else in ~/.cache".into(),
        category: Category::User,
        paths: vec!["~/.cache".into()],
        size,
        files,
        needs_admin: false,
        caution: Some("Applications rebuild these; first launch may be slower".into()),
        selected_by_default: false,
        details: biggest
            .into_iter()
            .take(8)
            .filter(|(b, _)| *b > 0)
            .map(|(b, p)| format!("{p} — {}", crate::util::human_bytes(b)))
            .collect(),
    });
    out
}

