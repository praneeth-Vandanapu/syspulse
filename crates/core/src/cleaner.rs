//  Purpose: Cache cleaner. Scans well-known cache locations, reports their size
//           and location, and cleans the ones the user selects.
//             * User targets (home caches, browsers, dev tools) are cleaned
//               directly by the app.
//             * System targets (APT cache, journal, old snaps...) are cleaned
//               by the privileged helper, which only accepts the fixed target
//               IDs defined here - never arbitrary paths.
