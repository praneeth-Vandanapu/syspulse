#[derive(Debug, Clone, Copy, Serialize, PartialEq, Eq)]
#[serde(rename_all = "lowercase")]
pub enum Category {
    System,
    User,
    Browser,
    Developer,
}

#[derive(Debug, Clone, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct CleanTarget {
    pub id: String,
    pub title: String,
    pub description: String,
    pub category: Category,
    /// Locations involved (shown to the user).
    pub paths: Vec<String>,
    /// Reclaimable bytes (estimate for journal / autoremove).
    pub size: u64,
    pub files: u64,
    pub needs_admin: bool,
    /// Shown as a warning next to the item; such items start unselected.
    pub caution: Option<String>,
    pub selected_by_default: bool,
    /// Extra detail lines (e.g. packages autoremove would delete).
    pub details: Vec<String>,
}

#[derive(Debug, Clone, Serialize, Default)]
#[serde(rename_all = "camelCase")]
pub struct CleanReport {
    pub freed_bytes: u64,
    pub cleaned: Vec<String>,
    pub errors: Vec<String>,
}

